import { z } from 'zod';
import { MasterListQueryBase } from './masters';
import { MasterCodeSchema, OptionalText, optional } from './validators';

export const ITEM_ERROR_CODES = [
  'DUPLICATE_NAME',
  'DUPLICATE_ITEM',
  'INVALID_CATEGORY',
  'INVALID_UNIT',
  'INVALID_STATUS',
  'SELF_APPROVAL_NOT_ALLOWED',
] as const;

export type ItemErrorCode = (typeof ITEM_ERROR_CODES)[number];

export const HSN_PATTERN = /^(\d{4}|\d{6}|\d{8})$/;
export const GST_RATE_PATTERN = /^\d{1,3}(\.\d{1,2})?$/;
export const MAX_GST_RATE = 100;
export const MAX_UNIT_DECIMALS = 3;

export const CATEGORY_CODE_PREFIX = 'IG-';
export const CATEGORY_CODE_DIGITS = 4;
export const ITEM_CODE_PREFIX = 'ITM-';
export const ITEM_CODE_DIGITS = 6;

/** Formats a sequence number as a master code. Never truncates: 10000 becomes IG-10000. */
export function formatMasterCode(prefix: string, digits: number, value: number | bigint): string {
  return `${prefix}${value.toString().padStart(digits, '0')}`;
}

/** Trim and collapse inner whitespace, so values that differ only by spacing compare equal. */
export function normalizeText(value: string): string {
  return value.trim().replace(/\s+/g, ' ');
}

const NormalizedText = (max: number) =>
  z.string().transform(normalizeText).pipe(z.string().min(1).max(max));

export const HsnSchema = z.string().trim().regex(HSN_PATTERN);

/** Sent and returned as a string ("18" or "18.00") so no decimal value passes through a float. */
export const GstRateSchema = z.coerce
  .string()
  .trim()
  .regex(GST_RATE_PATTERN)
  .refine((value) => Number(value) <= MAX_GST_RATE);

// ---------- Units ----------

export const UnitFields = z.object({
  name: z.string().trim().min(1).max(60),
  decimalPlaces: z.coerce.number().int().min(0).max(MAX_UNIT_DECIMALS),
});

export const CreateUnitRequest = UnitFields.extend({ code: MasterCodeSchema });

export type CreateUnitRequest = z.infer<typeof CreateUnitRequest>;

/** `code` may be repeated unchanged; a different one is CODE_IMMUTABLE. */
export const UpdateUnitRequest = UnitFields.extend({ code: MasterCodeSchema.optional() });

export type UpdateUnitRequest = z.infer<typeof UpdateUnitRequest>;

export const UnitListQuery = MasterListQueryBase.extend({
  sortBy: z.enum(['code', 'name', 'createdAt']).default('code'),
});

export type UnitListQuery = z.infer<typeof UnitListQuery>;

export const UnitResponse = z.object({
  id: z.uuid(),
  code: z.string(),
  name: z.string(),
  decimalPlaces: z.number().int(),
  isActive: z.boolean(),
  createdAt: z.string(),
  updatedAt: z.string(),
  canManage: z.boolean(),
});

export type UnitResponse = z.infer<typeof UnitResponse>;

export const PagedUnitsResponse = z.object({
  items: z.array(UnitResponse),
  total: z.number().int(),
  page: z.number().int(),
  pageSize: z.number().int(),
});

export type PagedUnitsResponse = z.infer<typeof PagedUnitsResponse>;

