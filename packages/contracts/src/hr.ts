export const HR_ERROR_CODES = [
  'DUPLICATE_NAME',
  'DUPLICATE_EMPLOYEE_CODE',
  'DUPLICATE_EMAIL',
  'INVALID_COMPANY',
  'INVALID_DESIGNATION',
  'INVALID_WORK_LOCATION',
  'INVALID_EMAIL_DOMAIN',
  'INVALID_DATES',
  'COMPANY_IMMUTABLE',
  'CODE_CHANGE_REMARKS_REQUIRED',
  'EMPLOYEE_NOT_ACTIVE',
  'USER_ALREADY_LINKED',
  'INVALID_USER',
  'USERNAME_TAKEN',
  'USER_EMAIL_TAKEN',
] as const;

export type HrErrorCode = (typeof HR_ERROR_CODES)[number];

export const DESIGNATION_CODE_PREFIX = 'DSG-';
export const DESIGNATION_CODE_DIGITS = 4;
export const EMPLOYEE_NO_PREFIX = 'EMP-';
export const EMPLOYEE_NO_DIGITS = 6;

/** Client employee code after normalising (OQ-143 c), e.g. UIEPL/HO/001. */
export const EMPLOYEE_CODE_PATTERN = /^[A-Z0-9][A-Z0-9/._-]{0,39}$/;

/** Removes all spaces and uppercases, so codes that differ only by case or spacing compare equal (OQ-136). */
export function normalizeEmployeeCode(value: string): string {
  return value.replace(/\s+/g, '').toUpperCase();
}

export const EmployeeCodeSchema = z
  .string()
  .transform(normalizeEmployeeCode)
  .pipe(z.string().regex(EMPLOYEE_CODE_PATTERN));

const NormalizedText = (max: number) =>
  z.string().transform(normalizeText).pipe(z.string().min(1).max(max));

const IsoDate = z.string().regex(ISO_DATE_PATTERN);

const OfficialEmailSchema = z.string().trim().toLowerCase().max(254).pipe(z.email());

