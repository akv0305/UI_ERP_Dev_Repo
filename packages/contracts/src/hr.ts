export type PagedDesignationsResponse = z.infer<typeof PagedDesignationsResponse>;

// ---------- Employees ----------

/** Blank = not recorded. PROJECT needs a project; site is optional (OQ-138). */
export const WORK_LOCATION_TYPES = ['HEAD_OFFICE', 'PROJECT'] as const;

export const WorkLocationType = z.enum(WORK_LOCATION_TYPES);

export type WorkLocationType = z.infer<typeof WorkLocationType>;

/** Worked out from the leaving date: LEFT once it is today or earlier, IST (OQ-134, OQ-141). */
export const EMPLOYEE_STATUSES = ['ACTIVE', 'LEFT'] as const;

export const EmployeeStatus = z.enum(EMPLOYEE_STATUSES);

export type EmployeeStatus = z.infer<typeof EmployeeStatus>;

/** Mandatory: code and full name (OQ-139), plus company on create (OQ-140). Employee No. is set by the API. */
export const EmployeeFields = z.object({
  code: EmployeeCodeSchema,
  fullName: NormalizedText(120),
  designationId: optional(z.uuid()),
  workLocationType: optional(WorkLocationType),
  projectId: optional(z.uuid()),
  siteId: optional(z.uuid()),
  dateOfJoining: optional(IsoDate),
  dateOfLeaving: optional(IsoDate),
  officialEmail: optional(OfficialEmailSchema),
  mobile: optional(PhoneSchema),
});

export const CreateEmployeeRequest = EmployeeFields.extend({ companyId: z.uuid() });

export type CreateEmployeeRequest = z.infer<typeof CreateEmployeeRequest>;

/** Company is fixed after create. A changed code needs remarks (CODE_CHANGE_REMARKS_REQUIRED). */
export const UpdateEmployeeRequest = EmployeeFields.extend({
  codeChangeRemarks: OptionalText(500),
});

export type UpdateEmployeeRequest = z.infer<typeof UpdateEmployeeRequest>;

export const EmployeeListQuery = MasterListQueryBase.extend({
  companyId: z.uuid().optional(),
  designationId: z.uuid().optional(),
  status: EmployeeStatus.optional(),
  sortBy: z.enum(['employeeNo', 'code', 'fullName', 'createdAt']).default('employeeNo'),
});

export type EmployeeListQuery = z.infer<typeof EmployeeListQuery>;

export const EmployeeDesignationSummary = z.object({
  id: z.uuid(),
  code: z.string(),
  name: z.string(),
  isActive: z.boolean(),
});

export type EmployeeDesignationSummary = z.infer<typeof EmployeeDesignationSummary>;

export const EmployeeUserSummary = z.object({
  id: z.uuid(),
  username: z.string(),
  isActive: z.boolean(),
});

export type EmployeeUserSummary = z.infer<typeof EmployeeUserSummary>;

export const EmployeeResponse = z.object({
  id: z.uuid(),
  employeeNo: z.string(),
  code: z.string(),
  fullName: z.string(),
  /** name = the company's legal name. */
  company: ScopeTargetSummary,
  designation: EmployeeDesignationSummary.nullable(),
  workLocationType: WorkLocationType.nullable(),
  project: ScopeTargetSummary.nullable(),
  site: ScopeTargetSummary.nullable(),
  dateOfJoining: z.string().nullable(),
  dateOfLeaving: z.string().nullable(),
  officialEmail: z.string().nullable(),
  mobile: z.string().nullable(),
  status: EmployeeStatus,
  user: EmployeeUserSummary.nullable(),
  isActive: z.boolean(),
  createdAt: z.string(),
  updatedAt: z.string(),
  /** True when the user may edit, deactivate or reactivate this employee. */
  canManage: z.boolean(),
  /** True when no user is linked, the employee is active and not Left, and the user may create one. */
  canCreateUser: z.boolean(),
});

export type EmployeeResponse = z.infer<typeof EmployeeResponse>;

export const PagedEmployeesResponse = z.object({
  items: z.array(EmployeeResponse),
  total: z.number().int(),
  page: z.number().int(),
  pageSize: z.number().int(),
});

export type PagedEmployeesResponse = z.infer<typeof PagedEmployeesResponse>;

